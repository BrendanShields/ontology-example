"""Compile the LinkML sources into the artefacts the gates and the apps run on.

    ontology/workflow.yaml        -> JSON Schema (frontmatter validation)
                                  -> SHACL shapes (graph validation)
    ontology/domains/<ctx>.yaml   -> Pydantic types and JSON Schema for the app
                                  -> with the app's code, the bindings manifest:
                                     which function produces each bound term

The artefacts are committed. `onto gen --check` regenerates them in memory and
fails if a committed file differs, so a schema change that was not compiled, or
a generated file edited by hand, is caught in CI.
"""

from __future__ import annotations

import contextlib
import difflib
import json
import os
from collections.abc import Callable, Iterator
from dataclasses import dataclass
from pathlib import Path

from .config import Config, Context
from .glossary import Glossary

NOTICE = "GENERATED by `onto gen` from {source}. Do not edit: change the source and regenerate."


class GeneratorUnavailable(RuntimeError):
    """The LinkML generators are not installed."""


@dataclass(frozen=True)
class Target:
    path: Path
    source: Path
    # (source path relative to root, notice) -> file content, or None for "no such file"
    render: Callable[[str, str], str | None]


@dataclass(frozen=True)
class Result:
    path: str
    status: str  # "written" | "unchanged" | "drift" | "removed"
    diff: str = ""


def targets(cfg: Config) -> list[Target]:
    found = [
        Target(cfg.workflow_json_schema, cfg.workflow_schema, _json_schema),
        Target(cfg.workflow_shacl, cfg.workflow_schema, _shacl),
    ]
    for ctx in cfg.contexts.values():
        if ctx.pydantic is not None:
            found.append(Target(ctx.pydantic, ctx.schema, _pydantic))
        if ctx.json_schema is not None:
            found.append(Target(ctx.json_schema, ctx.schema, _json_schema))
        if ctx.glossary_json is not None:
            found.append(Target(ctx.glossary_json, ctx.schema, _glossary_json(ctx)))
        if ctx.bindings_json is not None:
            found.append(Target(ctx.bindings_json, ctx.schema, _bindings_json(cfg, ctx)))
    return found


def generate(cfg: Config, *, check: bool = False) -> list[Result]:
    """Write every artefact, or with check=True report the ones that are out of date."""
    _require_linkml()
    results: list[Result] = []
    with _working_directory(cfg.root):  # generators embed the source path: keep it relative
        for target in targets(cfg):
            source = cfg.rel(target.source)
            content = target.render(source, NOTICE.format(source=source))
            rel = cfg.rel(target.path)
            current = target.path.read_text(encoding="utf-8") if target.path.is_file() else None
            if current == content:
                if content is not None:
                    results.append(Result(rel, "unchanged"))
            elif check:
                diff = "".join(
                    difflib.unified_diff(
                        (current or "").splitlines(keepends=True),
                        (content or "").splitlines(keepends=True),
                        fromfile=f"{rel} (committed)",
                        tofile=f"{rel} (generated from {source})",
                        n=1,
                    )
                )
                results.append(Result(rel, "drift", diff))
            elif content is None:
                target.path.unlink()
                results.append(Result(rel, "removed"))
            else:
                target.path.parent.mkdir(parents=True, exist_ok=True)
                target.path.write_text(content, encoding="utf-8")
                results.append(Result(rel, "written"))
    return results


# --- renderers -----------------------------------------------------------------


def _json_schema(source: str, notice: str) -> str:
    from linkml.generators.jsonschemagen import JsonSchemaGenerator

    schema = json.loads(JsonSchemaGenerator(source).serialize())
    return json.dumps({"$comment": notice, **schema}, indent=2) + "\n"


def _glossary_json(ctx: Context) -> Callable[[str, str], str]:
    """The definitions of a context as plain JSON, for an app to quote at runtime.

    An app that explains a term to a model or a person reads the definition
    from here, so the wording cannot drift from the ontology.
    """

    def render(source: str, notice: str) -> str:
        terms = {}
        for term in Glossary(ctx).terms.values():
            entry: dict = {"kind": term.kind, "definition": term.definition}
            if term.values:
                entry["values"] = list(term.values)
            if term.parent:
                entry["of"] = term.parent
            terms[term.name] = entry
        return (
            json.dumps({"$comment": notice, "context": ctx.name, "terms": terms}, indent=2) + "\n"
        )

    return render


def _bindings_json(cfg: Config, ctx: Context) -> Callable[[str, str], str | None]:
    """Which function produces each rule and computed slot the glossary binds.

    Unlike the other artefacts this one is compiled from the app's code as well
    as from the schema, so that moving or deleting a producing function shows
    up as drift. A context that binds nothing has no such file.
    """

    def render(source: str, notice: str) -> str | None:
        from . import rules

        bindings, _ = rules.scan(cfg, ctx, Glossary(ctx))
        if not bindings:
            return None
        return json.dumps({"$comment": notice, **rules.manifest(ctx, bindings)}, indent=2) + "\n"

    return render


def _pydantic(source: str, notice: str) -> str:
    from linkml.generators.pydanticgen import PydanticGenerator

    return f"# {notice}\n{PydanticGenerator(source).serialize().rstrip()}\n"


def _shacl(source: str, notice: str) -> str:
    """SHACL shapes, re-serialised so the file is readable and stable under regeneration.

    Shapes are open (`closed=False`): frontmatter is already closed by the JSON
    Schema, and the graph carries inferred types that a closed shape would reject.
    """
    from linkml.generators.shaclgen import ShaclGenerator
    from rdflib import BNode, Graph, Namespace
    from rdflib.collection import Collection

    sh = Namespace("http://www.w3.org/ns/shacl#")
    raw = Graph().parse(data=ShaclGenerator(source, closed=False).serialize(), format="turtle")

    # Shapes without a single property constraint say nothing: these are the
    # mixins that only carry a PROV class. Leave them out.
    for shape in set(raw.subjects(sh.targetClass, None)):
        if (shape, sh.property, None) not in raw:
            for ignored in raw.objects(shape, sh.ignoredProperties):
                Collection(raw, ignored).clear()
            raw.remove((shape, None, None))

    # The generator labels blank nodes arbitrarily. Rename each property shape
    # after its node shape, order and path so the Turtle writer always emits
    # them in the same, meaningful order.
    rename: dict = {}
    for shape, prop in raw.subject_objects(sh.property):
        order = raw.value(prop, sh.order)
        path = raw.value(prop, sh.path)
        rename[prop] = BNode(f"{_local(shape)}-{int(order or 0):03d}-{_local(path)}")

    pretty = Graph()
    for prefix, namespace in raw.namespaces():
        pretty.bind(prefix, namespace)
    for s, p, o in raw:
        pretty.add((rename.get(s, s), p, rename.get(o, o)))
    return f"# {notice}\n{pretty.serialize(format='turtle').strip()}\n"


def _local(iri) -> str:
    return str(iri).rsplit("#", 1)[-1].rsplit("/", 1)[-1]


def _require_linkml() -> None:
    try:
        import linkml  # noqa: F401
    except ImportError as exc:
        raise GeneratorUnavailable(
            "`onto gen` needs the LinkML generators: install onto-cli with the 'gen' extra "
            "(`uv sync` at the repository root does this)"
        ) from exc


@contextlib.contextmanager
def _working_directory(path: Path) -> Iterator[None]:
    previous = Path.cwd()
    os.chdir(path)
    try:
        yield
    finally:
        os.chdir(previous)
