"""`onto init`: put the ontology layer into a git repository that does not have it.

The files come from the templates packaged with onto:

* templates/synced/ is a copy of this framework's own ontology/ and .claude/,
  regenerated by tools/sync_templates.py and never edited by hand;
* templates/static/ holds what an adopting repository needs in a different
  form than the framework's own repository has it.

Nothing that exists is overwritten. A file that is there is left alone and
reported, and the three files a repository usually has already (.gitignore,
Makefile, .claude/settings.json) are added to, never rewritten.
"""

from __future__ import annotations

import copy
import json
import re
import subprocess
from dataclasses import dataclass
from importlib import resources
from pathlib import Path, PurePosixPath

from .config import load_config

# The placeholders of the templates. Each is replaced as exact text and nothing else is.
ONTO_CMD = "{{onto_cmd}}"
# Where the framework's own files spell out the project folder to reach onto. An adopting
# repository's command has to work from any folder inside it, so it is rendered the same.
ONTO_ANCHORED = "{{onto_anchored}}"
BASE_URI = "{{base_uri}}"
# In a permission rule of the settings template: each file nobody edits by hand.
# Which files those are is a fact of the adopting repository's onto.toml.
GENERATED = "{{generated}}"

# Template folders have plain names, so that no packaging tool drops them.
HIDDEN = {"claude": ".claude"}
SETTINGS = "claude/settings.json"
SETTINGS_CHECK = "guard --check-settings"  # the gate over .claude/settings.json
CLAUDE_LAYER = ("claude/", "tools/")  # the synced files that only the Claude Code layer needs

WRITTEN, EXISTS, MERGED, UNCHANGED, SKIPPED, BESIDE = (
    "written",
    "exists",
    "merged",
    "unchanged",
    "skipped",
    "beside",
)

_CONTEXT = re.compile(r"[a-z][a-z0-9_-]*\Z")
_RESERVED = ("linkml",)  # the prefix of the glossary template's own imports


def _prefix(context: str) -> str:
    return re.sub(r"[^a-z0-9]", "", context)


def _as_glob(path: str) -> str:
    """A domain path as the gates match it: from the repository root, and a glob.

    A bare folder or a leading `./` matches no file, and a layer that matches
    no file is a layer the vocabulary gate does not check.
    """
    path = path.strip()
    while path.startswith("./"):
        path = path[2:]
    if path and not any(char in path for char in "*?"):
        path = path.rstrip("/") + "/**"
    return path


@dataclass(frozen=True)
class Options:
    root: Path
    context: str = "app"
    domain_path: str = ""  # default: src/<context>/domain/**
    base_uri: str = "https://example.org"
    onto_cmd: str = "uv run onto"
    claude: bool = True
    ci: bool = True

    def __post_init__(self) -> None:
        if not _CONTEXT.match(self.context):
            raise ValueError(
                f"--context '{self.context}' must be lower case letters, digits, '-' or '_', "
                "starting with a letter: it names a file and a table in onto.toml"
            )
        if _prefix(self.context) in _RESERVED:
            raise ValueError(
                f"--context '{self.context}' gives the prefix '{_prefix(self.context)}', which "
                "every glossary already declares: choose another name"
            )
        if not self.domain_path:
            package = self.context.replace("-", "_")
            object.__setattr__(self, "domain_path", f"src/{package}/domain/**")
        object.__setattr__(self, "domain_path", _as_glob(self.domain_path))
        layer = PurePosixPath(self.domain_path.split("*", 1)[0])
        if layer.is_absolute() or ".." in layer.parts or len(layer.parts) < 2:
            raise ValueError(
                f"--domain-path '{self.domain_path}' must be a glob inside the repository with a "
                "folder above the domain layer, such as src/app/domain/**: the generated types "
                "are written to that folder"
            )
        if not re.fullmatch(r"https?://[^\s/\"<>\\^`{|}]+(/[^\s\"<>\\^`{|}]*)?", self.base_uri):
            raise ValueError(
                f"--base-uri '{self.base_uri}' must be an http or https URI without spaces, "
                "quotes or angle brackets"
            )
        object.__setattr__(self, "base_uri", self.base_uri.rstrip("/"))
        if not self.onto_cmd.strip():
            raise ValueError("--onto-cmd must not be empty")

    @property
    def tokens(self) -> dict[str, str]:
        layer = PurePosixPath(self.domain_path.split("*", 1)[0])
        return {
            "{{onto_cmd_quoted}}": json.dumps(self.onto_cmd),
            ONTO_CMD: self.onto_cmd,
            ONTO_ANCHORED: self.onto_cmd,
            BASE_URI: self.base_uri,
            "{{context}}": self.context,
            "{{prefix}}": _prefix(self.context),
            "{{domain_path}}": self.domain_path,
            "{{code_dir}}": layer.parent.as_posix(),
        }


@dataclass(frozen=True)
class Step:
    """What happened to one file."""

    status: str
    path: str  # repository-relative
    note: str = ""


def render(data: bytes, tokens: dict[str, str]) -> bytes:
    for token, value in tokens.items():
        data = data.replace(token.encode(), value.encode())
    return data


def templates(folder: str) -> dict[str, bytes]:
    """Template files of one folder, by their path inside it."""
    found: dict[str, bytes] = {}

    def walk(node, prefix: str) -> None:
        for child in sorted(node.iterdir(), key=lambda entry: entry.name):
            if child.is_dir():
                if child.name != "__pycache__":
                    walk(child, f"{prefix}{child.name}/")
            else:
                found[prefix + child.name] = child.read_bytes()

    walk(resources.files("onto") / "templates" / folder, "")
    return found


def destination(rel: str) -> str:
    """Where a synced template lands in a repository."""
    head, _, rest = rel.partition("/")
    return f"{HIDDEN[head]}/{rest}" if head in HIDDEN else rel


def git_root(start: Path | None = None) -> Path:
    done = subprocess.run(
        ["git", "rev-parse", "--show-toplevel"],
        cwd=start or Path.cwd(),
        capture_output=True,
        text=True,
        check=False,
    )
    if done.returncode != 0 or not done.stdout.strip():
        raise ValueError("onto init works in a git repository: run `git init` here first")
    return Path(done.stdout.strip()).resolve()


# --- the scaffold ----------------------------------------------------------------


def scaffold(options: Options) -> list[Step]:
    """Write every file the gates need that is not there yet. Returns what happened to each."""
    root, tokens = options.root, options.tokens
    static = templates("static")
    steps: list[Step] = []

    def put(rel: str, data: bytes) -> None:
        path = root / rel
        if path.exists():
            steps.append(Step(EXISTS, rel))
            return
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(data)
        steps.append(Step(WRITTEN, rel))

    put("onto.toml", render(static["onto.toml"], tokens))
    cfg = load_config(root)

    synced = templates("synced")
    for rel, data in synced.items():
        if rel == SETTINGS or (not options.claude and rel.startswith(CLAUDE_LAYER)):
            continue
        put(destination(rel), render(data, tokens))

    context = cfg.contexts.get(options.context)
    if context is None:
        steps.append(
            Step(
                SKIPPED,
                f"ontology/domains/{options.context}.yaml",
                f"onto.toml has no [contexts.{options.context}]: add the table, "
                "then run `onto init` again",
            )
        )
    else:
        put(cfg.rel(context.schema), render(static["glossary.yaml"], tokens))
    put(f"{cfg.rel(cfg.work_dir)}/README.md", render(static["work-README.md"], tokens))

    steps.append(_add_lines(root, ".gitignore", static["gitignore"].decode()))
    put("onto.mk", _for_layer(render(static["onto.mk"], tokens), options, "\n"))
    steps.append(_include_in_makefile(root))
    if options.ci:
        put(
            ".github/workflows/ontology-gates.yml",
            _for_layer(render(static["ontology-gates.yml"], tokens), options, "\n\n"),
        )
    if options.claude:
        ours = _replace_in_strings(json.loads(synced[SETTINGS]), ONTO_CMD, options.onto_cmd)
        steps.append(_settings(root, expand_generated(ours, never_edited(cfg))))
        steps.append(_claude_md(root, render(static["CLAUDE.md"], tokens)))
    return steps


def _for_layer(data: bytes, options: Options, separator: str) -> bytes:
    """Without the Claude Code layer there are no settings to check: leave that step out."""
    if options.claude:
        return data
    parts = data.decode().split(separator)
    return separator.join(part for part in parts if SETTINGS_CHECK not in part).encode()


def _appended(current: str, addition: str) -> str:
    """`current` with a block added after a blank line, whatever it ended with."""
    if not current.strip():
        return addition + "\n"
    return current.rstrip("\n") + "\n\n" + addition + "\n"


def _add_lines(root: Path, rel: str, wanted: str) -> Step:
    """Append the lines of `wanted` that the file does not have yet."""
    path = root / rel
    if not path.exists():
        path.write_text(wanted, encoding="utf-8")
        return Step(WRITTEN, rel)
    current = path.read_text(encoding="utf-8")
    have = {line.strip() for line in current.splitlines()}
    entries = [line for line in wanted.splitlines() if not line.startswith("#")]
    if all(line.strip() in have for line in entries):
        return Step(UNCHANGED, rel)
    missing = [line for line in wanted.splitlines() if line.strip() not in have]
    path.write_text(_appended(current, "\n".join(missing)), encoding="utf-8")
    return Step(MERGED, rel, "added the lines for evidence and provenance")


def _include_in_makefile(root: Path) -> Step:
    """The targets live in onto.mk. A Makefile only gains the line that includes it."""
    include = "include onto.mk"
    # Listed, not probed: on a case-insensitive disk every spelling "exists".
    present = {entry.name for entry in root.iterdir()}
    name = next((n for n in ("GNUmakefile", "makefile", "Makefile") if n in present), None)
    if name is None:
        (root / "Makefile").write_text(f"{include}\n", encoding="utf-8")
        return Step(WRITTEN, "Makefile")
    path = root / name
    current = path.read_text(encoding="utf-8")
    if re.search(r"^-?include\b.*\bonto\.mk\b", current, re.M):
        return Step(UNCHANGED, path.name)
    addition = f"# The ontology gates: onto-gen, onto-check, onto-view.\n{include}"
    path.write_text(_appended(current, addition), encoding="utf-8")
    return Step(MERGED, path.name, "added `include onto.mk`")


def _replace_in_strings(value, old: str, new: str):
    if isinstance(value, str):
        return value.replace(old, new)
    if isinstance(value, list):
        return [_replace_in_strings(entry, old, new) for entry in value]
    if isinstance(value, dict):
        return {key: _replace_in_strings(entry, old, new) for key, entry in value.items()}
    return value


def never_edited(cfg) -> list[str]:
    """What `onto gen` and a test run write, as permission-rule paths from the repository root."""
    from .gen import targets

    generated = {cfg.rel(target.path) for target in targets(cfg)}
    return [f"/{path}" for path in sorted(generated | {f"{cfg.rel(cfg.evidence_dir)}/**"})]


def expand_generated(settings: dict, paths: list[str]) -> dict:
    """The settings with each permission rule on GENERATED repeated for every path."""
    expanded = copy.deepcopy(settings)
    permissions = expanded.get("permissions", {})
    for kind, rules in permissions.items():
        if not isinstance(rules, list):
            continue
        permissions[kind] = [
            each
            for rule in rules
            for each in (
                [rule.replace(GENERATED, p) for p in paths] if GENERATED in rule else [rule]
            )
        ]
    return expanded


class Unmergeable(Exception):
    """The settings file is not shaped in a way that can be added to safely."""


def merge_settings(theirs: dict, ours: dict) -> dict:
    """`theirs` with our permissions and hooks added. Nothing of theirs is changed or removed."""
    if not isinstance(theirs, dict):
        raise Unmergeable("it is not a JSON object")
    merged = copy.deepcopy(theirs)
    for key, value in ours.items():
        if key == "permissions":
            permissions = merged.setdefault("permissions", {})
            if not isinstance(permissions, dict):
                raise Unmergeable("`permissions` is not an object")
            for kind, rules in value.items():
                if not isinstance(rules, list):
                    permissions.setdefault(kind, rules)
                    continue
                present = permissions.setdefault(kind, [])
                if not isinstance(present, list):
                    raise Unmergeable(f"`permissions.{kind}` is not a list")
                present.extend(rule for rule in rules if rule not in present)
        elif key == "hooks":
            hooks = merged.setdefault("hooks", {})
            if not isinstance(hooks, dict):
                raise Unmergeable("`hooks` is not an object")
            for event, groups in value.items():
                present = hooks.setdefault(event, [])
                if not isinstance(present, list):
                    raise Unmergeable(f"`hooks.{event}` is not a list")
                commands = hook_commands(present)
                present.extend(group for group in groups if not hook_commands([group]) <= commands)
        else:
            merged.setdefault(key, value)
    return merged


def hook_commands(groups: list) -> set[str]:
    found: set[str] = set()
    for group in groups:
        hooks = group.get("hooks", []) if isinstance(group, dict) else []
        found.update(
            hook["command"]
            for hook in hooks
            if isinstance(hook, dict) and isinstance(hook.get("command"), str)
        )
    return found


def _settings(root: Path, ours: dict) -> Step:
    rel = ".claude/settings.json"
    path = root / rel
    text = json.dumps(ours, indent=2) + "\n"
    if not path.exists():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
        return Step(WRITTEN, rel)
    try:
        theirs = json.loads(path.read_text(encoding="utf-8"))
        merged = merge_settings(theirs, ours)
    except (json.JSONDecodeError, UnicodeDecodeError, Unmergeable) as exc:
        note = (
            f"{rel} could not be added to safely ({exc}): "
            "copy the permissions and hooks from this file into it by hand"
        )
        return _beside(root, ".claude/settings.onto.json", text.encode(), note)
    if merged == theirs:
        return Step(UNCHANGED, rel)
    path.write_text(json.dumps(merged, indent=2) + "\n", encoding="utf-8")
    return Step(MERGED, rel, "added the onto permissions and hooks")


def _claude_md(root: Path, section: bytes) -> Step:
    path = root / "CLAUDE.md"
    if not path.exists():
        path.write_bytes(section)
        return Step(WRITTEN, "CLAUDE.md")
    if "onto.toml" in path.read_text(encoding="utf-8", errors="replace"):
        return Step(UNCHANGED, "CLAUDE.md")
    note = "CLAUDE.md exists: copy this section into it, then delete this file"
    return _beside(root, "CLAUDE.onto.md", section, note)


def _beside(root: Path, rel: str, data: bytes, note: str) -> Step:
    """Write what could not be merged next to the file it belongs in, unless that is taken too."""
    path = root / rel
    if path.exists():
        same = path.read_bytes() == data
        return Step(UNCHANGED if same else EXISTS, rel, "" if same else f"not written. {note}")
    path.write_bytes(data)
    return Step(BESIDE, rel, note)


# --- the command -----------------------------------------------------------------


def arguments(parser) -> None:
    defaults = Options(Path("."))
    parser.add_argument(
        "--context",
        default=defaults.context,
        metavar="NAME",
        help=f"the bounded context to start a glossary for (default: {defaults.context})",
    )
    parser.add_argument(
        "--domain-path",
        default="",
        metavar="GLOB",
        help="the domain layer of that context (default: src/<context>/domain/**)",
    )
    parser.add_argument(
        "--base-uri",
        default=defaults.base_uri,
        metavar="URI",
        help=f"the namespace the ontologies are published under (default: {defaults.base_uri})",
    )
    parser.add_argument(
        "--onto-cmd",
        default=defaults.onto_cmd,
        metavar="COMMAND",
        help=f"how hooks, make and CI run onto (default: '{defaults.onto_cmd}')",
    )
    parser.add_argument("--no-claude", action="store_true", help="leave out the Claude Code layer")
    parser.add_argument("--no-ci", action="store_true", help="leave out the CI workflow")


def run(args) -> int:
    from . import gen

    options = Options(
        root=git_root(),
        context=args.context,
        domain_path=args.domain_path,
        base_uri=args.base_uri,
        onto_cmd=args.onto_cmd,
        claude=not args.no_claude,
        ci=not args.no_ci,
    )
    steps = scaffold(options)
    for step in steps:
        print(f"{step.status:9} {step.path}" + (f"  ({step.note})" if step.note else ""))
    kept = sum(1 for step in steps if step.status == EXISTS)
    if kept:
        print(f"onto init: {kept} file(s) were already there and were left as they are")

    cfg = load_config(options.root)
    foreign = _not_generated(cfg)
    if foreign:
        print(
            f"onto init: `onto gen` was not run. {', '.join(foreign)} would be overwritten and "
            "onto did not generate it. Point the context's generated files somewhere else in "
            "onto.toml, then run `onto gen`.",
        )
        return 1
    try:
        results = gen.generate(cfg)
    except gen.GeneratorUnavailable as exc:
        print(f"onto init: the files are in place, but {exc}. Then run `onto gen`.")
        return 1
    for result in results:
        print(f"{result.status:9} {result.path}")
    print(
        "onto init: done. Next: `onto validate`, then `onto overview` to read the starter "
        "glossary. docs/adopting.md of the onto repository has the rest."
    )
    return 0


def _not_generated(cfg) -> list[str]:
    """Generation targets that hold something `onto gen` did not write."""
    from .gen import NOTICE, targets

    mark = NOTICE.split("{", 1)[0]
    return [
        cfg.rel(target.path)
        for target in targets(cfg)
        if target.path.is_file()
        and mark not in target.path.read_text(encoding="utf-8", errors="replace")[:1000]
    ]
