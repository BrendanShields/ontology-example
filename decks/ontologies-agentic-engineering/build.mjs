import fs from "node:fs";
import path from "node:path";
import url from "node:url";
import { esc } from "./src/kit.mjs";

const STEP = 3;
const dir = path.dirname(url.fileURLToPath(import.meta.url));
const slideDir = path.join(dir, "src", "slides");

const files = fs
  .readdirSync(slideDir)
  .filter((f) => /^s\d\d\.mjs$/.test(f))
  .sort();
// The running order of the talk. Each slide answers the question the one before it raises.
// Ids are file names and do not follow this order; a file not listed here goes to the end.
const ORDER = [
  "s01", // an agent guesses; structure gives it one permitted route
  "s02", // ontologies already run everyday products
  "s03", // what it costs an engineering team to lack one, and the fix
  "s17", // what the same map does for the people: less to hold in their heads
  "s07", // what the word means, next to three it is confused with
  "s08", // what the rules buy: inference
  "s09", // how it is written down: four standards
  "s10", // nouns are not enough: logic and actions
  "s06", // "this was tried in the 1980s"
  "s05", // "the model could just read it, or search it"
  "s04", // which part of the system does which job
  "s12", // one turn of the loop
  "s13", // what the agent gets to see
  "s11", // how people keep trust at volume, and where the why lives
  "s14", // all of it on one change
  "s15", // where it goes wrong, and how to start
  "s16",
];
const loaded = [];
for (const f of files) {
  loaded.push((await import(url.pathToFileURL(path.join(slideDir, f)).href)).default);
}
const place = (s) => (ORDER.includes(s.id) ? ORDER.indexOf(s.id) : ORDER.length);
const slides = loaded.sort((a, b) => place(a) - place(b));

const indent = (s, n) =>
  s
    .split("\n")
    .map((line) => (line ? " ".repeat(n) + line : line))
    .join("\n");

const sections = slides
  .map((s) => {
    const lines = s.title
      .map((line) => `<span class="ln"><span class="in">${esc(line)}</span></span>`)
      .join("");
    const header = s.bare
      ? null
      : [
          `  <header class="hd">`,
          `    <p class="eyebrow"><span class="ln"><span class="in">${esc(s.eyebrow)}</span></span></p>`,
          `    <h2 class="title">${lines}</h2>`,
          `  </header>`,
        ].join("\n");
    return [
      `<section class="slide" id="${s.id}" data-holds="${s.holds}" data-label="${esc(s.title.join(" "))}">`,
      header,
      `  <div class="body">`,
      `    <svg viewBox="0 0 1920 1080" aria-hidden="true">`,
      indent(s.body(), 6),
      `    </svg>`,
      s.html ? indent(s.html(), 4) : null,
      `  </div>`,
      s.bare ? null : `  <p class="ref" data-layout-ignore>${esc(s.ref ?? "")}</p>`,
      `</section>`,
    ]
      .filter((line) => line != null)
      .join("\n");
  })
  .join("\n");

let hold = 0;
const island = {
  slides: slides.map((s) => {
    const first = hold;
    hold += s.holds;
    const fragments = [];
    for (let i = 0; i < s.holds; i++) fragments.push((first + i) * STEP);
    const entry = {
      sceneId: `${String(slides.indexOf(s) + 1).padStart(2, "0")} ${s.title.join(" ")}`,
      startTime: first * STEP,
      endTime: (first + s.holds - 1) * STEP + 0.04,
      fragments,
    };
    const notesFile = path.join(dir, "src", "notes", `${s.id}.md`);
    entry.notes = fs.existsSync(notesFile) ? fs.readFileSync(notesFile, "utf8").trim() : "";
    return entry;
  }),
};
const total = hold * STEP;

const rail = slides.map((_, i) => `<i style="left: ${i * 14}px"></i>`).join("");
const css = slides
  .filter((s) => s.css)
  .map((s) => s.css.trimEnd())
  .join("\n");

const html = fs
  .readFileSync(path.join(dir, "src", "template.html"), "utf8")
  .replace("<html", "<!-- Generated by build.mjs from src/. Edit src/ and run `node build.mjs`. -->\n<html")
  .replace("/*__SLIDE_CSS__*/", () => css)
  .replace("__ISLAND__", () => indent(JSON.stringify(island, null, 2).replace(/</g, "\\u003c"), 6))
  .replaceAll("__TOTAL__", String(total))
  .replace("__STEP__", String(STEP))
  .replace("__SLIDES__", () => indent(sections, 10))
  .replace("__RAIL__", () => indent(rail, 12));

fs.writeFileSync(path.join(dir, "index.html"), html);

let at = 0;
const times = {};
for (const s of slides) {
  times[s.id] = Array.from({ length: s.holds }, (_, i) => (at + i) * STEP);
  at += s.holds;
  const cues = (island.slides[slides.indexOf(s)].notes.match(/^\[next\]$/gm) ?? []).length;
  if (cues !== s.holds - 1) console.warn(`warn ${s.id}: notes have ${cues} [next] cues for ${s.holds} holds`);
  if (!/class="mk"[^>]*data-b="1"/.test(s.body())) console.warn(`warn ${s.id}: no marker anchor on the first hold`);
}
const asked = process.argv.indexOf("--times");
if (asked > 0) {
  console.log(process.argv.slice(asked + 1).flatMap((id) => times[id] ?? []).join(","));
  process.exit(0);
}

const words = island.slides.reduce((n, s) => n + s.notes.split(/\s+/).filter(Boolean).length, 0);
console.log(`${slides.length} slides, ${hold} holds, ${total} s, ${words} words of notes`);
